def complete_initialization(root: Path, control_module) -> None:
    """After bootstrap-closeout PASS: the explicit NOT_STARTED -> COMPLETE transition, WI-000 closed."""
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, check=True, capture_output=True, text=True,
                          env=dict(os.environ, GIT_OPTIONAL_LOCKS="0")).stdout.strip()
    replace_once(root / "FIRST_START.md", r"INITIALIZATION_STATUS: NOT_STARTED", "INITIALIZATION_STATUS: COMPLETE")
    state_path = root / "project_control/project-state.v1.json"
    state = load_json(state_path)
    state["initialization"].update(status="COMPLETE", completed_at=datetime.now(timezone.utc).isoformat(),
                                   baseline_head=head, closeout_evidence=["project_control.py bootstrap-closeout PASS"])
    dump_json(state_path, state)
    item_path = root / "project_control/work-items/WI-000.json"
    item = load_json(item_path)
    item.update(status="DONE", close_head=head)
    dump_json(item_path, item)
    roadmap_path = root / "docs/governance/roadmap-state.v1.json"
    roadmap = load_json(roadmap_path)
    roadmap["work_items"][0].update(status="DONE", integration_state="HISTORICAL")
    dump_json(roadmap_path, roadmap)
    replace_once(root / "docs/governance/ROADMAP.md", r"\| AUTHORIZED \| UNMERGED \|", "| DONE | HISTORICAL |")
    registry = root / "docs/governance/WORKTREE_REGISTRY.md"
    registry.write_text(control_module.render_registry_entry(registry.read_text(encoding="utf-8"), item, "CLOSED"),
                        encoding="utf-8")


def evidence_report(root: Path, work_item_id: str, gate: str, level: str, artifact: Path, summary: str) -> str:
    subject = subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, check=True, capture_output=True, text=True,
                             env=dict(os.environ, GIT_OPTIONAL_LOCKS="0")).stdout.strip()
    report = {"schema_version": "1.0.0", "work_item_id": work_item_id, "gate": gate, "result": "PASS",
              "level": level, "subject_commit": subject, "runtime_target": "NOT_APPLICABLE",
              "recorded_at": datetime.now(timezone.utc).isoformat(), "summary": summary,
              "artifacts": [{"path": str(artifact.relative_to(root)), "sha256": sha256_of(artifact)}]}
    path = root / f"reports/evidence/{work_item_id}/{gate}.json"
    dump_json(path, report)
    return str(path.relative_to(root))


def changed_paths(root: Path, files: list[str]) -> list[str]:
    return [name for name in files if (root / name).exists()]


def play(source: Path, work: Path, verbose: bool = False) -> Transcript:
    root = work / "hello-squelette"
    root.mkdir()
    t = Transcript(root, verbose=verbose)

    # 1 ----------------------------------------------------------------------
    t.section("1. A fresh copy of the template becomes a project")
    exported = export_template(source, root)
    # No file count here: the public mirror of the template carries one file fewer than the private
    # repository (its export tool), and a transcript that counted them drifted between the two.
    assert exported, "the template's tracked tree is what the demo copies"
    t.say("The tracked tree of the template is copied without `.git`: a new project starts "
          "its own history. Git is initialized, the pristine copy is committed as the autonomous baseline, then "
          "the commit gate is installed outside the worktree — where no commit can carry it away — and every "
          "commit is audited from now on.")
    t.git("init", "-b", "main")
    t.run(["git", "add", "--", *exported], shown="git add -- <every exported file, explicitly>")
    t.git("commit", "-q", "-m", "init: pristine copy of the template")
    t.control("install-gate", key="install_gate")
    t.control("status", key="status_fresh")

    # 2 ----------------------------------------------------------------------
    t.section("2. Bootstrap Mode: only initialization paths are writable")
    t.say("Before FIRST_START is closed, the controller only accepts the governance files of the interview. "
          "Business code is refused, whatever the agent intends.")
    t.control("bootstrap-audit", key="bootstrap_audit")
    t.control("bootstrap-preflight", "--path", "modules/hello/greeting.py", key="bootstrap_refused", expect=1)
    t.control("bootstrap-preflight", "--path", "docs/governance/PROJECT_CHARTER.md",
              "--path", "docs/governance/HUMAN_DECISIONS.md", "--path", "project_control/work-items/WI-000.json",
              key="bootstrap_allowed")

    # 3 ----------------------------------------------------------------------
    t.section("3. The Project Owner answers the interview; the agent records the answers")
    control_module = load_controller(root)
    scripted_interview(root, control_module)
    t.say("A scripted Project Owner validates the Charter, the initial architecture, ADR-0001 and the "
          "Anti-Octopus review, chooses the `PLAIN` reporting style, and records HD-001, which authorizes the "
          "initialization Work Item WI-000. The agent writes these records, audits them and commits them — the "
          "hook replays `bootstrap-audit` on the staged state before accepting the commit.")
    t.control("bootstrap-audit", key="bootstrap_audit_records")
    interview_files = ["project_control/project-state.v1.json",
                       "docs/governance/PROJECT_CHARTER.md", "docs/architecture/PROJECT_ARCHITECTURE_MAP.md",
                       "docs/architecture/INITIAL_ARCHITECTURE.md",
                       "docs/adr/ADR-0001-initial-architecture-boundaries.md",
                       "docs/governance/HUMAN_DECISIONS.md", "docs/governance/REPOSITORY_STATUS.md",
                       "project_control/work-items/WI-000.json", "project_control/conversations/CONV-000.json",
                       "docs/governance/roadmap-state.v1.json", "docs/governance/ROADMAP.md",
                       "docs/governance/WORKTREE_REGISTRY.md"]
    t.run(["git", "add", "--", *interview_files], shown="git add -- <the interview records, explicitly>")
    t.git("commit", "-q", "-m", "init: FIRST_START interview recorded (HD-001)")
    t.say("The closeout checks every deliverable of the interview at once.")
    t.control("bootstrap-closeout", "--path", "FIRST_START.md", "--path", "project_control/project-state.v1.json",
              key="closeout")
    complete_initialization(root, control_module)
    t.say("`INITIALIZATION_STATUS` goes to `COMPLETE` in FIRST_START.md and in Project State together, WI-000 is "
          "closed, and the transition is committed explicitly. From now on the canonical branch only accepts "
          "administrative records, reports and provenance: this transition commit is the one the hook lets "
          "through only under an explicit human mandate, echoed in the transcript.")
    transition_files = ["FIRST_START.md", "project_control/project-state.v1.json",
                        "project_control/work-items/WI-000.json", "docs/governance/roadmap-state.v1.json",
                        "docs/governance/ROADMAP.md", "docs/governance/WORKTREE_REGISTRY.md"]
    t.run(["git", "add", "--", *transition_files], shown="git add -- <the closeout transition, explicitly>")
    t.run(["git", "commit", "-q", "-m", "init: FIRST_START closed (HD-001)"],
          shown='PROJECT_CONTROL_HOOK_OVERRIDE="HD-001: FIRST_START closeout" git commit -q -m "init: FIRST_START closed (HD-001)"',
          env_extra={"PROJECT_CONTROL_HOOK_OVERRIDE": "HD-001: FIRST_START closeout"}, key="closeout_commit")
    t.control("audit", key="audit_after_init")
    t.control("status", key="status_at_rest")

    # 4 ----------------------------------------------------------------------
    t.section("4. A human decision authorizes one Work Item")
    t.say("The Project Owner decides: add a greeting module under `modules/hello/`, nothing else. "
          "`create-work-item` records the decision HD-002, the Work Item, its conversation reference, the roadmap, "
          "the branch registry and the path classification in one transaction, and commits them itself.")
    t.control("create-work-item", "WI-001",
              "--title", "Greeting module",
              "--objective", "Add greet(name) under modules/hello/ with its tests.",
              "--owner", OWNER,
              "--human-decision", "HD-002",
              "--decision", "Authorize WI-001: a greeting module under modules/hello/, with tests, and nothing else.",
              "--authorized-by", OWNER,
              "--branch", "work/wi-001-greeting",
              "--path", "modules/hello",
              "--conflict-gate", "INDEPENDENT",
              "--direct-impact", "modules/hello",
              "--indirect-impact", "None: the module has no consumer yet",
              "--authority-impact", "NONE",
              "--concurrent-work-impact", "NONE",
              "--code", "APPLICABLE", "--tests", "APPLICABLE", "--integration", "APPLICABLE",
              "--deployment", "NOT_APPLICABLE", "--runtime-proof", "NOT_APPLICABLE",
              "--runtime-target", "NOT_APPLICABLE",
              "--close-condition", "Tests pass and the branch is integrated into main.",
              key="create")

    # 5 ----------------------------------------------------------------------
    t.section("5. The agent proves it has read the authorities, then starts")
    t.say("`context-manifest` lists the documents that govern this Work Item, with their SHA-256 and a global "
          "digest. `start` refuses without that digest, and never prints it in its own output: the agent has to "
          "go and get it from the authorities as they stand right now. What this proves is narrow and exact — the "
          "work started from the current text of every authority, and changing any one of them invalidates the "
          "proof until it is acknowledged again. No mechanism can prove that a mind was changed by reading.")
    manifest = t.control("context-manifest", "WI-001", key="manifest")
    digest = next(line.split(": ", 1)[1].strip() for line in manifest.stdout.splitlines()
                  if line.startswith("MANIFEST_DIGEST: "))
    t.control("start", "WI-001", key="start_refused", expect=1)
    t.control("start", "WI-001", "--authorities-digest", digest, key="start")
    t.control("status", key="status_in_progress")

    # 6 ----------------------------------------------------------------------
    t.section("6. Outside the authorized scope, the preflight refuses")
    t.say("The agent drifts: it writes a billing module nobody asked for and stages it. The preflight names the "
          "path and fails; the hook would refuse the commit for the same reason.")
    sneaky = root / "modules/billing/invoice.py"
    sneaky.parent.mkdir(parents=True)
    sneaky.write_text(SNEAKY_PY, encoding="utf-8")
    t.git("add", "--", "modules/billing/invoice.py")
    t.control("preflight", "WI-001", key="preflight_refused", expect=1)
    t.git("rm", "-q", "--cached", "--", "modules/billing/invoice.py")
    sneaky.unlink()
    sneaky.parent.rmdir()
    t.say("The drift is undone. Inside the authorized scope — the greeting module and its tests, staged with "
          "explicit paths — the same preflight passes.")
    hello = root / "modules/hello"
    hello.mkdir(parents=True)
    (hello / "greeting.py").write_text(GREETING_PY, encoding="utf-8")
    (hello / "test_greeting.py").write_text(TEST_GREETING_PY, encoding="utf-8")
    t.git("add", "--", "modules/hello/greeting.py", "modules/hello/test_greeting.py")
    t.control("preflight", "WI-001", "--path", "modules/hello/greeting.py", "--path", "modules/hello/test_greeting.py",
              key="preflight_pass")

    # 7 ----------------------------------------------------------------------
    t.section("7. Work, tests, integration")
    tests = t.run([sys.executable, "-B", "-m", "unittest", "discover", "-s", "modules/hello", "-p", "test_*.py"],
                  shown="python3 -B -m unittest discover -s modules/hello -p 'test_*.py'", key="tests")
    t.git("commit", "-q", "-m", "feat(hello): greeting module (WI-001)")
    feature_commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, check=True, capture_output=True,
                                    text=True, env=dict(os.environ, GIT_OPTIONAL_LOCKS="0")).stdout.strip()
    t.git("switch", "-q", "main")
    t.git("merge", "--no-ff", "-q", "-m", "merge: integrate WI-001", "work/wi-001-greeting")

    # 8 ----------------------------------------------------------------------
    t.section("8. Evidence, then close")
    t.say("Each applicable gate needs a JSON report pointing at a committed artifact with its SHA-256, for the "
          "exact integrated commit. `close` verifies the reports, the declared business commit, the branch "
          "integration and the proof of reading, then records `DONE` and commits.")
    evidence_dir = root / "reports/evidence/WI-001"
    evidence_dir.mkdir(parents=True)
    tests_artifact = evidence_dir / "tests.txt"
    tests_artifact.write_text((tests.stdout + tests.stderr), encoding="utf-8")
    integration_artifact = evidence_dir / "integration.txt"
    log = subprocess.run(["git", "log", "--oneline", "-3"], cwd=root, check=True, capture_output=True, text=True,
                         env=dict(os.environ, GIT_OPTIONAL_LOCKS="0")).stdout
    integration_artifact.write_text("Integrated into main by a no-fast-forward merge:\n" + log, encoding="utf-8")
    tests_report = evidence_report(root, "WI-001", "tests", "TESTED", tests_artifact,
                                   "unittest discover on modules/hello: all tests pass.")
    integration_report = evidence_report(root, "WI-001", "integration", "INTEGRATED", integration_artifact,
                                         "Branch work/wi-001-greeting merged into main.")
    t.run(["git", "add", "--", tests_report, integration_report, "reports/evidence/WI-001/tests.txt",
           "reports/evidence/WI-001/integration.txt"], shown="git add -- reports/evidence/WI-001/*")
    t.git("commit", "-q", "-m", "evidence: WI-001 tests and integration")
    t.control("close", "WI-001", "--commit", feature_commit,
              "--test-evidence", tests_report, "--integration-evidence", integration_report, key="close")
    t.say("The roadmap view — what happened, what is next, what waits for the Project Owner — is generated from "
          "the records, in the reporting style the Project Owner chose; the controller commits the Markdown view "
          "itself, the HTML page is ignored by Git.")
    t.control("roadmap-view", "--write", key="roadmap_view")
    t.control("status", key="status_done")
    t.control("audit", key="audit_done")
    t.git("log", "--oneline", "--graph", key="log")
    t.say("Every administrative step is a commit of its own, made by the controller on the canonical branch. "
          "The project is at rest again: no active Work Item, one proven change, a readable history.")
    return t


