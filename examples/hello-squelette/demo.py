def readme_block(text: str) -> tuple[int, int] | None:
    begin = text.find(BEGIN)
    end = text.find(END)
    if begin < 0 or end < 0 or end < begin:
        return None
    return begin + len(BEGIN), end


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="refresh TRANSCRIPT.md and the README block")
    group.add_argument("--check", action="store_true", help="fail if TRANSCRIPT.md or the README block drifted")
    parser.add_argument("--quiet", action="store_true", help="do not print the transcript")
    parser.add_argument("--verbose", action="store_true",
                        help="keep every PASS line of the controller's reports (the committed transcript folds them)")
    args = parser.parse_args(argv)

    state = load_json(ROOT / "project_control/project-state.v1.json")
    if state.get("repository_role") != "PROJECT_TEMPLATE" or state["initialization"]["status"] != "NOT_STARTED":
        print("hello-squelette replays the template itself: run it from a NOT_STARTED checkout of the template.")
        return 2

    with tempfile.TemporaryDirectory(prefix="hello-squelette-") as temporary:
        transcript = play(ROOT, Path(temporary), verbose=args.verbose and not (args.write or args.check))
    full = transcript.render_full()
    excerpt = transcript.render_excerpt()

    if args.write:
        TRANSCRIPT.write_text(full, encoding="utf-8")
        text = README.read_text(encoding="utf-8")
        span = readme_block(text)
        if span is None:
            # Without the markers there is nothing to keep honest: refuse rather than write half.
            print(f"README.md has no {BEGIN} … {END} block: TRANSCRIPT.md written, but the README "
                  "block cannot be refreshed. Restore the two markers.")
            return 1
        README.write_text(text[:span[0]] + "\n" + excerpt + text[span[1]:], encoding="utf-8")
        print(f"written: {TRANSCRIPT.relative_to(ROOT)} and the README block")
        return 0

    if args.check:
        drift = []
        if not TRANSCRIPT.exists() or TRANSCRIPT.read_text(encoding="utf-8") != full:
            drift.append(str(TRANSCRIPT.relative_to(ROOT)))
        text = README.read_text(encoding="utf-8")
        span = readme_block(text)
        if span is None:
            # A missing block used to skip the check silently: removing two comments disabled
            # the very guarantee the README announces on its first screen.
            drift.append(f"README.md (no {BEGIN} … {END} block)")
        elif text[span[0]:span[1]] != "\n" + excerpt:
            drift.append("README.md (hello-squelette block)")
        if drift:
            print("DRIFT: " + ", ".join(drift) + " — regenerate with: python3 -B examples/hello-squelette/demo.py --write")
            return 1
        print("hello-squelette: TRANSCRIPT.md and the README block match the controller's output.")
        return 0

    if not args.quiet:
        print(full)
    return 0


if __name__ == "__main__":
    sys.exit(main())
